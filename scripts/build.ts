// Run from a plugin directory (`bun run build` there). Bundles each entry point of that plugin
// (the list below) to the same-named .mjs, so consumers run plain `node X.mjs` with no Bun and no
// node_modules. Packages come from the plugin's own node_modules.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, relative, resolve } from "node:path";

const banner = "// generated by bun run build; edit the .ts file";
const pluginRoot = process.cwd();
const repoRoot = resolve(import.meta.dir, "..");
const pluginDir = relative(repoRoot, pluginRoot);
if (!pluginDir || pluginDir.startsWith("..")) {
  throw new Error("Run the build from a plugin directory.");
}
// Bundle comments name each source relative to the repository root.
process.chdir(repoRoot);

// Browser entries bundle npm packages and run in the page, not in Node. Each is minified and
// carries the full licence text of the packages it inlines.
const browser: Record<string, string[]> = {
  "plugins/factory/skills/lifecycle/dashboard.ts": ["marked", "dompurify"],
};

function licenses(packages: string[]) {
  const text = packages.flatMap((name) => {
    const dir = resolve(pluginRoot, "node_modules", name);
    const { version } = JSON.parse(readFileSync(resolve(dir, "package.json"), "utf8"));
    return ["LICENSE", "LICENSE-MPL"]
      .filter((file) => existsSync(resolve(dir, file)))
      .map((file) => `${name} ${version} (${file})\n\n${readFileSync(resolve(dir, file), "utf8").trim()}`);
  });
  return `/*!\n${text.join("\n\n").replaceAll("*/", "* /")}\n*/\n`;
}

// Relative imports stay inside the plugin. The bundler inlines every `.ts` file that an entry
// imports, so each entry is one file. Bundled libraries import their own files.
const importPolicy = (entry: string): Bun.BunPlugin => ({
  name: "import-policy",
  setup(build) {
    build.onResolve({ filter: /^\.\.?\// }, ({ path, importer }) => {
      if (importer.includes("/node_modules/")) return undefined;
      check(entry, path, importer);
      return undefined;
    });
  },
});

function check(entry: string, path: string, importer: string) {
  const inside = relative(pluginRoot, resolve(dirname(importer || entry), path));
  if (inside.startsWith("..") || isAbsolute(inside)) {
    throw new Error(`${entry}: import "${path}" leaves the plugin.`);
  }
}

// Only the files listed here become bundles. A module that an entry imports, a test and a type
// file are not entries.
const pluginEntries: Record<string, string[]> = {
  "plugins/factory": [
    "plugins/factory/skills/lifecycle/dashboard.ts",
    "plugins/factory/skills/lifecycle/factory.ts",
  ],
  "plugins/coordination": [
    "plugins/coordination/skills/coordinator/board-data.ts",
    "plugins/coordination/skills/coordinator/coordinator.ts",
  ],
};

const entries = pluginEntries[pluginDir];
if (!entries) throw new Error(`No entry list for ${pluginDir} in scripts/build.ts.`);
for (const entry of entries) {
  if (!existsSync(entry)) throw new Error(`Entry ${entry} does not exist.`);
}

for (const entry of entries) {
  const result = await Bun.build({
    entrypoints: [entry],
    outdir: dirname(entry),
    naming: "[name].mjs",
    target: browser[entry] ? "browser" : "node",
    format: "esm",
    banner: browser[entry] ? `${banner}\n${licenses(browser[entry])}` : banner,
    minify: Boolean(browser[entry]),
    plugins: [importPolicy(entry)],
  });
  if (!result.success) {
    for (const log of result.logs) console.error(log);
    process.exit(1);
  }
  // Bun inlines the absolute path of a CommonJS module as its `__filename`; keep it relative so
  // the output does not depend on the checkout location.
  for (const { path } of result.outputs) {
    writeFileSync(path, readFileSync(path, "utf8").replaceAll(`${repoRoot}/`, ""));
  }
}

console.log(`built ${entries.length} bundle${entries.length === 1 ? "" : "s"}`);
