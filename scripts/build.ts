// Bundles every plugins/**/*.ts entry point to the same-named .mjs, so consumers
// run plain `node X.mjs` with no Bun and no node_modules.
import { existsSync, readFileSync } from "node:fs";
import { dirname, isAbsolute, relative, resolve } from "node:path";

const banner = "// generated by bun run build; edit the .ts file";

// Browser entries bundle npm packages and run in the page, not in Node. Each is minified and
// carries the full licence text of the packages it inlines.
const browser: Record<string, string[]> = {
  "plugins/factory/skills/lifecycle/dashboard-markdown.ts": ["marked", "dompurify"],
};

function licenses(packages: string[]) {
  const text = packages.flatMap((name) => {
    const dir = resolve("node_modules", name);
    const { version } = JSON.parse(readFileSync(resolve(dir, "package.json"), "utf8"));
    return ["LICENSE", "LICENSE-MPL"]
      .filter((file) => existsSync(resolve(dir, file)))
      .map((file) => `${name} ${version} (${file})\n\n${readFileSync(resolve(dir, file), "utf8").trim()}`);
  });
  return `/*!\n${text.join("\n\n").replaceAll("*/", "* /")}\n*/\n`;
}

// A plugin ships alone, so it may only import from its own directory.
function boundary(entry: string) {
  const [top, name] = entry.split("/");
  return resolve(top, name);
}

// Relative imports stay inside the entry's boundary. Sibling .mjs imports stay imports; each
// bundle is one module and the layout is unchanged. Bundled libraries import their own files.
const importPolicy = (entry: string): Bun.BunPlugin => ({
  name: "import-policy",
  setup(build) {
    const root = boundary(entry);
    build.onResolve({ filter: /^\.\.?\/.*\.mjs$/ }, ({ path, importer }) => {
      if (importer.includes("/node_modules/")) return undefined;
      check(entry, root, path, importer);
      return { path, external: true };
    });
    build.onResolve({ filter: /^\.\.?\// }, ({ path, importer }) => {
      if (importer.includes("/node_modules/")) return undefined;
      check(entry, root, path, importer);
      return undefined;
    });
  },
});

function check(entry: string, root: string, path: string, importer: string) {
  const inside = relative(root, resolve(dirname(importer || entry), path));
  if (inside.startsWith("..") || isAbsolute(inside)) {
    throw new Error(`${entry}: import "${path}" leaves ${relative(".", root) || "the repository"}.`);
  }
}

const entries = [...new Bun.Glob("plugins/**/*.ts").scanSync(".")]
  .filter((file) => !file.includes("node_modules/") && !file.endsWith(".d.ts"))
  .sort();

for (const entry of entries) {
  const result = await Bun.build({
    entrypoints: [entry],
    outdir: dirname(entry),
    naming: "[name].mjs",
    target: browser[entry] ? "browser" : "node",
    format: "esm",
    banner: browser[entry] ? `${banner}\n${licenses(browser[entry])}` : banner,
    minify: Boolean(browser[entry]),
    plugins: [importPolicy(entry)],
  });
  if (!result.success) {
    for (const log of result.logs) console.error(log);
    process.exit(1);
  }
}

console.log(`built ${entries.length} bundle${entries.length === 1 ? "" : "s"}`);
